content = open(sys.argv[1]).read()
sys.stdout.write(content.replace('bash .claude/hooks/', 'bash ' + sys.argv[2] + '/'))
" "$SCRIPT_DIR/rules/project-settings-example.json" "$abs_hook_dir")
