for hook_type, entries in new_data.get("hooks", {}).items():
    if hook_type not in existing["hooks"]:
        existing["hooks"][hook_type] = []
    existing_cmds = {json.dumps(h, sort_keys=True) for group in existing["hooks"][hook_type] for h in group.get("hooks", [])}
    # Also track basenames for path-normalized dedup (prevents relative + absolute duplicates)
    existing_basenames = {h.get("command","").split("/")[-1] for group in existing["hooks"][hook_type] for h in group.get("hooks", [])}
    for entry in entries:
        new_cmds = {json.dumps(h, sort_keys=True) for h in entry.get("hooks", [])}
        new_basenames = {h.get("command","").split("/")[-1] for h in entry.get("hooks", [])}
        if new_basenames.issubset(existing_basenames):
            # Script already registered (possibly under different path form) — update command + matcher
            new_matcher = entry.get("matcher", "")
            for existing_entry in existing["hooks"][hook_type]:
                entry_basenames = {h.get("command","").split("/")[-1] for h in existing_entry.get("hooks", [])}
                if new_basenames == entry_basenames:
                    # Update command to new form (e.g. relative -> absolute)
                    for new_h in entry.get("hooks", []):
                        for ex_h in existing_entry.get("hooks", []):
                            if new_h.get("command","").split("/")[-1] == ex_h.get("command","").split("/")[-1]:
                                ex_h["command"] = new_h["command"]
                    if new_matcher and existing_entry.get("matcher", "") != new_matcher:
                        existing_entry["matcher"] = new_matcher
        elif not new_cmds.issubset(existing_cmds):
            existing["hooks"][hook_type].append(entry)
            existing_cmds |= new_cmds
            existing_basenames |= new_basenames
tmp = target_file + ".tmp"
with open(tmp, "w") as f:
    json.dump(existing, f, indent=2)
    f.write("\n")
os.replace(tmp, target_file)
' "$target_file" "$NEW_HOOKS_JSON"

  if python3 -m json.tool "$target_file" >/dev/null 2>&1; then
    echo "  [ok] Merged hooks into $(basename "$target_file")"
    echo "  [ok] JSON validated"
  else
    echo "[ERROR] JSON validation failed for $target_file" >&2
    exit 1
  fi
}

# ---------------------------------------------------------------------------
# merge_context_mode_hooks
# ---------------------------------------------------------------------------
# Registers context-mode's five upstream hooks (PostToolUse, PreToolUse,
# PreCompact, SessionStart, UserPromptSubmit) in the target settings.json
# using the CLI dispatcher form `context-mode hook claude-code <event>`.
#
# Dedup strategy differs from merge_settings_json: this function uses a
# SUBSTRING match on the command string (`context-mode hook claude-code
# <event>`) rather than basename-split. Basename dedup would false-match any
# unrelated hook whose command ends with `/posttooluse`, `/precompact`, etc.
#
# Idempotent: re-running heals matcher drift but does not duplicate entries.
# Fail-open: if python3 exits non-zero (corrupt JSON, missing python3), we
# print a warning and return 0 so setup.sh continues.
#
# Only called from install_project() guarded by INSTALL_CONTEXT_MODE=true.
merge_context_mode_hooks() {
  local target_file="$1"

  if [ "$DRY_RUN" = true ]; then
    echo "  [DRY RUN] Would merge context-mode upstream hooks into $target_file"
    return 0
  fi

  mkdir -p "$(dirname "$target_file")"

  # Resolve absolute dispatcher path from the settings.json path. `.claude`
  # is the parent of settings.json; the dispatcher lives at
  # `.claude/hooks/context-mode-hook-dispatch.sh`. Absolute paths are required
  # in settings.json hook commands because hooks may be invoked from any CWD.
  local claude_dir
  claude_dir="$(cd "$(dirname "$target_file")" && pwd -P)"
  local dispatch_abspath="$claude_dir/hooks/context-mode-hook-dispatch.sh"

  # Why a dispatcher helper instead of bare `npx -y context-mode@latest`:
  # concurrent hook fires (every tool call triggers PreToolUse+PostToolUse —
  # rapid Bash/Read/mcp__ sessions hit this constantly) race to refresh the
  # npx cache and fail with ENOTEMPTY during atomic rename of
  # ~/.npm/_npx/<hash>/. Failures are non-blocking (harness continues) but
  # silently skip capture for that event. The dispatcher short-circuits to a
  # globally-installed `context-mode` binary when present (no npx → no race)
  # and falls back to `npx -y context-mode@latest` only when no global
  # install exists. See hooks/project/context-mode-hook-dispatch.sh.
  #
  # Phase 57 G2/G3: write the canonical upstream-1.0.122 matcher inventory
  # unconditionally. Both install forms are supported in parallel — the plugin
  # form (`mcp__plugin_context-mode_context-mode__*`) is listed FIRST in each
  # matcher per G3 to document canonical-vs-legacy intent and to win the match
  # during transitional dual-registration states. The MCP-server form
  # (`mcp__context-mode__*`) follows as legacy. No version gate (G2): older
  # installs receive matchers they don't yet consume; upgrading to 1.0.122+
  # activates them with zero further config.
  #
  # PostToolUse: aligns to upstream POST_TOOL_USE_MATCHERS (closes #329 capture
  # gap via the wildcard `mcp__` matcher introduced in 1.0.122 #532).
  # PreToolUse: gains the three plugin-form ctx_execute matchers alongside the
  # existing MCP-server-form matchers.
  if ! python3 - "$target_file" "$dispatch_abspath" <<'PY'
import json, os, sys

target = sys.argv[1]
dispatch = sys.argv[2]

# Commands invoke the hook dispatcher which resolves context-mode (global
# install → fast path; npx fallback → first-run primes cache, no race after).
expected = {
    # Upstream 1.0.122 POST_TOOL_USE_MATCHERS (build/adapters/claude-code/hooks.js):
    #   ["Bash","Read","Write","Edit","NotebookEdit","Glob","Grep","TodoWrite",
    #    "TaskCreate","TaskUpdate","EnterPlanMode","ExitPlanMode","Skill",
    #    "Agent","AskUserQuestion","EnterWorktree","mcp__"]
    # We add `WebFetch` and `WebSearch` ahead of upstream because our project
    # captures those events for the search/fetch session-resolution pipeline.
    # These are additive: upstream's PostToolUse hook simply no-ops on them.
    "PostToolUse": {
        "matcher": "Bash|Read|Write|Edit|NotebookEdit|Glob|Grep|WebFetch|WebSearch|TodoWrite|TaskCreate|TaskUpdate|EnterPlanMode|ExitPlanMode|Skill|Agent|AskUserQuestion|EnterWorktree|mcp__",
        "command": f"bash {dispatch} posttooluse",
    },
    # Upstream 1.0.122 PRE_TOOL_USE_MATCHERS lists the plugin-form ctx tools
    # only; we list them FIRST per Phase 57 G3 ordering rule, then carry the
    # MCP-server-form matchers second as legacy coverage so older installs and
    # transitional dual-registration states both fire the hook.
    "PreToolUse": {
        "matcher": "Bash|WebFetch|Read|Grep|Agent|mcp__plugin_context-mode_context-mode__ctx_execute|mcp__plugin_context-mode_context-mode__ctx_execute_file|mcp__plugin_context-mode_context-mode__ctx_batch_execute|mcp__context-mode__ctx_execute|mcp__context-mode__ctx_execute_file|mcp__context-mode__ctx_batch_execute",
        "command": f"bash {dispatch} pretooluse",
    },
    "PreCompact": {
        "matcher": "",
        "command": f"bash {dispatch} precompact",
    },
    "SessionStart": {
        "matcher": "",
        "command": f"bash {dispatch} sessionstart",
    },
    "UserPromptSubmit": {
        "matcher": "",
        "command": f"bash {dispatch} userpromptsubmit",
    },
}

# Read existing settings.json — fail-open to {} on any read or parse error so
# we always produce a valid file.
try:
    with open(target) as f:
        data = json.load(f)
    if not isinstance(data, dict):
        data = {}
except (FileNotFoundError, json.JSONDecodeError, OSError):
    data = {}

if "hooks" not in data or not isinstance(data.get("hooks"), dict):
    data["hooks"] = {}

for event, spec in expected.items():
    want_matcher = spec["matcher"]
    want_cmd = spec["command"]
    # Two sentinels so we detect AND heal every prior phase-51 form:
    # - dispatcher (current)            → `context-mode-hook-dispatch.sh <event>`
    # - npx launcher (intermediate fix) → `npx ... context-mode@latest hook claude-code <event>`
    # - bare (early phase-51)           → `context-mode hook claude-code <event>`
    # The legacy sentinel REQUIRES both `context-mode` and the event phrase
    # in the command string — a tighter anchor than matching just
    # `hook claude-code <event>`, which would false-match any user-authored
    # shim whose command happens to contain that phrase (e.g. a hand-rolled
    # wrapper that translates an unrelated CLI's arguments). Both legitimate
    # legacy forms contain `context-mode` (bare: `context-mode hook ...`;
    # npx launcher: `... context-mode@latest ...`), so this anchoring is
    # safe for the upgrade path while reducing false-match surface area.
    sentinel_legacy_phrase = f"hook claude-code {event.lower()}"
    sentinel_dispatch = f"context-mode-hook-dispatch.sh {event.lower()}"

    if event not in data["hooks"] or not isinstance(data["hooks"].get(event), list):
        data["hooks"][event] = []

    # Substring search across all command entries in the event's list.
    found = False
    for group in data["hooks"][event]:
        if not isinstance(group, dict):
            continue
        for h in group.get("hooks", []) or []:
            if not isinstance(h, dict):
                continue
            cmd = h.get("command", "")
            if not isinstance(cmd, str):
                continue
            legacy_match = ("context-mode" in cmd) and (sentinel_legacy_phrase in cmd)
            if legacy_match or sentinel_dispatch in cmd:
                # Heal matcher drift — rewrite matcher to the upstream
                # default so all installs stay on the same tool-coverage
                # contract.
                if group.get("matcher", "") != want_matcher:
                    group["matcher"] = want_matcher
                # Heal command drift — rewrite to the dispatcher form if the
                # existing entry is an older phase-51 form (legacy bare or
                # intermediate npx launcher). The dispatcher eliminates the
                # npx ENOTEMPTY race that the launcher form suffers under
                # concurrent hook fires. User customizations are preserved:
                # - `bash /path/dispatch.sh <event> --verbose` survives
                #   because the dispatcher basename+event substring is present
                # - Any hand-written command containing
                #   `context-mode-hook-dispatch.sh <event>` (including flags
                #   or redirections) is left untouched.
                if sentinel_dispatch not in cmd:
                    h["command"] = want_cmd
                found = True
                break
        if found:
            break

    if found:
        print(f"  [ok] context-mode {event} hook already present")
    else:
        # Append at END of the event array so existing project hooks (ours)
        # stay at lower indices and fire first.
        data["hooks"][event].append({
            "matcher": want_matcher,
            "hooks": [{"type": "command", "command": want_cmd}],
        })
        print(f"  [ok] Registered context-mode {event} hook")

tmp = target + ".tmp"
with open(tmp, "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
os.replace(tmp, target)
PY
  then
    echo "  [warn] merge_context_mode_hooks: python3 failed; upstream context-mode hooks not registered"
    return 0
  fi

  if python3 -m json.tool "$target_file" >/dev/null 2>&1; then
    :
  else
    echo "  [warn] JSON validation failed for $target_file after context-mode hook merge" >&2
  fi

  # F1: Bust stale enforcer-form cache so the next Bash hook call re-probes.
  # The cache has no TTL — a mid-session plugin install would otherwise stay
  # masked as "not installed" until /tmp is cleared.
  rm -f /tmp/ctx-enforcer-* 2>/dev/null || true
}

