# Only runs for project installs. Follows the same prompt pattern as
# install_statusline: detect current state, prompt, merge on yes.

install_allowlist() {
  if [ "$INSTALL_PROJECT" != true ]; then
    return 0
  fi

  echo "[ALLOWLIST]"

  if [ "$DRY_RUN" = true ]; then
